ALTER TABLE projects ADD COLUMN evaluation_revision BIGINT NOT NULL DEFAULT 0;
ALTER TABLE projects ADD CONSTRAINT ck_projects_evaluation_revision CHECK (evaluation_revision >= 0);

CREATE TABLE environment_api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT NOT NULL REFERENCES environments(id),
    name VARCHAR(100) NOT NULL,
    public_id VARCHAR(32) NOT NULL,
    secret_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_api_keys_public_id UNIQUE (public_id),
    CONSTRAINT ck_api_keys_public_id CHECK (public_id ~ '^[a-f0-9]{32}$'),
    CONSTRAINT ck_api_keys_hash CHECK (secret_hash ~ '^[a-f0-9]{64}$'),
    CONSTRAINT ck_api_keys_revoked_at CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);
CREATE INDEX idx_api_keys_environment ON environment_api_keys(environment_id);

ALTER TABLE audit_events DROP CONSTRAINT ck_audit_action;
ALTER TABLE audit_events ADD CONSTRAINT ck_audit_action CHECK (action IN (
    'PROJECT_CREATED', 'PROJECT_UPDATED', 'PROJECT_DELETED',
    'FLAG_CREATED', 'FLAG_UPDATED', 'FLAG_DELETED', 'FLAG_CONFIGURATION_UPDATED',
    'API_KEY_CREATED', 'API_KEY_REVOKED'
));
