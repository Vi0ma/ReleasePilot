CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    project_key VARCHAR(100) NOT NULL,
    description VARCHAR(2000),
    owner_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_projects_owner_key UNIQUE (owner_id, project_key),
    CONSTRAINT ck_projects_key CHECK (project_key ~ '^[a-z0-9_-]+$')
);

CREATE TABLE environments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    name VARCHAR(100) NOT NULL,
    environment_key VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_environments_project_key UNIQUE (project_id, environment_key),
    CONSTRAINT uk_environments_id_project UNIQUE (id, project_id),
    CONSTRAINT ck_environments_key CHECK (environment_key ~ '^[a-z0-9_-]+$')
);

CREATE TABLE feature_flags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    flag_key VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_flags_project_key UNIQUE (project_id, flag_key),
    CONSTRAINT uk_flags_id_project UNIQUE (id, project_id),
    CONSTRAINT ck_flags_key CHECK (flag_key ~ '^[a-z0-9_-]+$')
);

CREATE TABLE flag_configurations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_flag_id BIGINT NOT NULL,
    environment_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    rollout_percentage INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_configurations_flag_environment UNIQUE (feature_flag_id, environment_id),
    CONSTRAINT fk_configurations_flag_project FOREIGN KEY (feature_flag_id, project_id)
        REFERENCES feature_flags(id, project_id),
    CONSTRAINT fk_configurations_environment_project FOREIGN KEY (environment_id, project_id)
        REFERENCES environments(id, project_id),
    CONSTRAINT ck_configurations_rollout CHECK (rollout_percentage BETWEEN 0 AND 100)
);
CREATE INDEX idx_configurations_project ON flag_configurations(project_id);
CREATE INDEX idx_configurations_environment_project ON flag_configurations(environment_id, project_id);

-- Historical project/entity identifiers survive resource deletion.
-- owner_user_id is retained for authorization after the project is deleted.
CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    owner_user_id BIGINT NOT NULL REFERENCES users(id),
    project_id BIGINT NOT NULL,
    action VARCHAR(40) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    entity_id BIGINT NOT NULL,
    metadata JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_audit_action CHECK (action IN (
        'PROJECT_CREATED', 'PROJECT_UPDATED', 'PROJECT_DELETED',
        'FLAG_CREATED', 'FLAG_UPDATED', 'FLAG_DELETED', 'FLAG_CONFIGURATION_UPDATED'))
);
CREATE INDEX idx_audit_project_owner_created ON audit_events(project_id, owner_user_id, created_at DESC, id DESC);
CREATE INDEX idx_audit_actor ON audit_events(actor_user_id);
CREATE INDEX idx_audit_owner ON audit_events(owner_user_id);
